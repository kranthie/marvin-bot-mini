"""Pack the generated robot model into one script file for the site's 3-D viewers.

Reads description/urdf/marvin_bot_mini_covers.urdf (the robot with its clip-on shells),
description/cad_model.yaml (each part's process, material and mass), robot.yaml, skeleton.yaml,
actuators.yaml and the part meshes in
description/meshes/, which `python -m cad.build` generates. Writes
site/public/guide/model/marvin_model.js, which sets window.MARVIN_MODEL: the joints, link masses,
every visual part with its category and assembly module, and the meshes, quantised and packed as
base64. The meshes are kept exact and carry no normals: the viewers smooth them in the browser
(site/src/scripts/marvin-render.js). A script file rather than JSON, so the pages also work when
opened straight from disk. Adapted from Marvin Bot's (one robot, servos drawn as boxes).

    pip install -e ".[cad]" && python -m cad.build && python site/scripts/build_model.py

The meshes are derived from the hardware design files (CERN-OHL-S-2.0).
"""

from __future__ import annotations

import argparse
import base64
import json
import math
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
import trimesh
import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "site" / "public" / "guide" / "model" / "marvin_model.js"
SOURCE = (
    "Generated by site/scripts/build_model.py from the Marvin Bot Mini repository: "
    "description/urdf/, description/cad_model.yaml and the code-CAD part meshes (CERN-OHL-S-2.0)."
)


def floats(text: str | None, n: int = 3) -> list[float]:
    return [float(x) for x in text.split()] if text else [0.0] * n


def rpy_matrix(r: float, p: float, y: float) -> np.ndarray:
    cr, sr, cp, sp, cy, sy = (
        math.cos(r),
        math.sin(r),
        math.cos(p),
        math.sin(p),
        math.cos(y),
        math.sin(y),
    )
    return np.array(
        [
            [cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
            [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
            [-sp, cp * sr, cp * cr],
        ]
    )


def transform(xyz: list[float], rpy: list[float]) -> np.ndarray:
    t = np.eye(4)
    t[:3, :3] = rpy_matrix(*rpy)
    t[:3, 3] = xyz
    return t


def parse_urdf(path: Path) -> tuple[dict, list[dict]]:
    root = ET.parse(path).getroot()
    links = {}
    for link in root.iter("link"):
        inertial = link.find("inertial")
        info = None
        if inertial is not None:
            info = {
                "mass": float(inertial.find("mass").get("value")),
                "com": floats(inertial.find("origin").get("xyz")),
            }
        visuals = []
        for v in link.iter("visual"):
            origin = v.find("origin")
            geom = list(v.find("geometry"))[0]
            mat = v.find("material")
            color = mat.find("color") if mat is not None else None
            visuals.append(
                {
                    "xyz": floats(origin.get("xyz") if origin is not None else None),
                    "rpy": floats(origin.get("rpy") if origin is not None else None),
                    "geom": geom.tag,
                    "attrib": dict(geom.attrib),
                    "mat": mat.get("name") if mat is not None else None,
                    "rgba": floats(color.get("rgba"), 4) if color is not None else [0.5] * 4,
                }
            )
        links[link.get("name")] = {"inertial": info, "visuals": visuals}
    joints = []
    for j in root.iter("joint"):
        lim = j.find("limit")
        origin = j.find("origin")
        joints.append(
            {
                "name": j.get("name"),
                "type": j.get("type"),
                "parent": j.find("parent").get("link"),
                "child": j.find("child").get("link"),
                "xyz": floats(origin.get("xyz")),
                "rpy": floats(origin.get("rpy")),
                "axis": floats(j.find("axis").get("xyz")),
                "lower": float(lim.get("lower")),
                "upper": float(lim.get("upper")),
                "effort": float(lim.get("effort")),
                "velocity": float(lim.get("velocity")),
            }
        )
    return links, joints


def module_of(link: str, cat: str) -> str:
    """The assembly module a part belongs to."""
    if cat == "cover":
        return "cover"
    if cat == "battery":
        return "battery"
    if link == "pelvis":
        return "pelvis"
    if link in ("neck_link", "head_link"):
        return "head"
    if any(k in link for k in ("hip", "thigh", "shin", "ankle", "foot")):
        return "leg"
    if any(k in link for k in ("shoulder", "arm", "palm", "jaw")):
        return "arm"
    return "torso"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=OUT)
    build(ap.parse_args().out)


def build(out: Path) -> None:
    desc = ROOT / "description"
    cad = yaml.safe_load((desc / "cad_model.yaml").read_text())
    robot = yaml.safe_load((desc / "robot.yaml").read_text())
    skel = yaml.safe_load((desc / "skeleton.yaml").read_text())
    acts = yaml.safe_load((desc / "actuators.yaml").read_text())
    links, joints = parse_urdf(desc / "urdf" / "marvin_bot_mini_covers.urdf")
    root = (set(links) - {j["child"] for j in joints}).pop()
    motor_of: dict[str, str] = {}
    for m in robot["motors"]:
        for side in ["left", "right"] if "{side}" in m["name"] else [None]:
            for d in m["drives"]:
                motor_of[d.replace("{side}", side) if side else d] = m["model"]

    def side_key(link: str, size) -> tuple:
        generic = link.replace("left_", "{s}_").replace("right_", "{s}_")
        return generic, tuple(round(x, 4) for x in size)

    boxed = ("compute", "battery", "electronics", "camera", "arm_frame", "head_frame")
    budget_boxes = {
        side_key(b["link"], b["size"]): b for b in skel["bodies"] if b["budget"] in boxed
    }
    box_names = {
        "compute": "Jetson Orin Nano Super developer kit (outline)",
        "battery": "3S Li-ion pack (outline)",
        "electronics": "power board, servo bus adapters and IMU (outline)",
        "camera": "head camera (outline)",
    }
    box_cat = {
        "compute": "compute",
        "battery": "battery",
        "electronics": "electronics",
        "camera": "sensors",
    }
    # the servo boxes are listed per link in motor order; match each to its joint by its centre
    servo_at = {}
    for m in robot["motors"]:
        for side in ["left", "right"] if "{side}" in m["name"] else [None]:
            (d,) = (x.replace("{side}", side) if side else x for x in m["drives"])
            servo_at[d] = m["model"]

    meshes = {}
    total = 0
    for link in links.values():
        for v in link["visuals"]:
            if v["geom"] == "mesh":
                stem = Path(v["attrib"]["filename"]).stem
                meshes[stem] = trimesh.load(desc / "meshes" / f"{stem}.stl")
                total += len(meshes[stem].faces)

    blob = bytearray()

    def add(arr: np.ndarray) -> int:
        while len(blob) % 4:
            blob.append(0)
        off = len(blob)
        blob.extend(arr.tobytes())
        return off

    # which joint each servo box drives: the joint whose motor sits on this link nearest the box
    mounts = {}
    for jn, j in ((j["name"], j) for j in joints):
        mounts.setdefault(j["parent"], []).append((jn, j["xyz"]))
    for name, mm in (skel.get("motor_mounts") or {}).items():
        for side in ["left", "right"] if name.startswith("left_") else [None]:
            jn = name.replace("left_", f"{side}_") if side else name
            link = mm["link"].replace("left_", f"{side}_") if side else mm["link"]
            xyz = list(mm["xyz"])
            if side == "right":
                xyz[1] = -xyz[1]
            mounts.setdefault(link, []).append((jn, xyz))

    def servo_joint(link: str, xyz: list[float], model: str) -> str:
        cands = [(jn, p) for jn, p in mounts.get(link, []) if servo_at.get(jn) == model]
        return min(cands, key=lambda c: float(np.linalg.norm(np.subtract(c[1], xyz))))[0]

    parts = []
    for lname, link in links.items():
        for v in link["visuals"]:
            p = {"link": lname, "xyz": v["xyz"], "rpy": v["rpy"], "rgba": v["rgba"]}
            mat = v["mat"]
            if v["geom"] == "mesh":
                stem = Path(v["attrib"]["filename"]).stem
                info = cad.get(stem, {})
                verts = np.asarray(meshes[stem].vertices, dtype=np.float64)
                faces = np.asarray(meshes[stem].faces, dtype=np.int64)
                lo = verts.min(0)
                span = np.maximum(verts.max(0) - lo, 1e-6)
                q = np.round((verts - lo) / span * 65535).astype(np.uint16)
                idx = faces.astype(np.uint16 if len(verts) < 65536 else np.uint32)
                p.update(
                    kind="mesh",
                    name=stem,
                    cat="cover" if info.get("process") == "cover" else "print",
                    material=info.get("material", mat),
                    process=info.get("process", "print"),
                    mass=info.get("mass"),
                    budget=info.get("budget"),
                    lo=lo.round(6).tolist(),
                    span=span.round(6).tolist(),
                    v=[add(q), len(verts)],
                    i=[add(idx), len(faces) * 3, idx.itemsize],
                )
            elif v["geom"] == "box":
                size = floats(v["attrib"]["size"])
                if mat in acts:  # a servo
                    p.update(
                        kind="box",
                        size=size,
                        cat="actuator",
                        name=f"{mat} servo",
                        model=mat,
                        joint=servo_joint(lname, v["xyz"], mat),
                    )
                else:
                    b = budget_boxes.get(side_key(lname, size))
                    kind = b["budget"] if b else "box"
                    p.update(
                        kind="box",
                        size=size,
                        cat=box_cat.get(kind, "print"),
                        name=box_names.get(kind, "box"),
                        mass=b["mass"] if b else None,
                        budget=kind,
                    )
            else:
                continue
            p["module"] = module_of(lname, p["cat"])
            parts.append(p)

    model = {
        "variant": "mini",
        "root": root,
        "joints": joints,
        "inertia": {n: links[n]["inertial"] for n in links},
        "parts": parts,
        # the viewers' field names: peak is the stall torque at the servo's rated 12 V
        "actuators": {
            k: {
                "peak_torque": acts[k]["stall_torque"],
                "rated_torque": acts[k]["rated_torque"],
                "no_load_speed_rpm": acts[k]["no_load_speed_rpm"],
                "gear_ratio": acts[k]["gear_ratio"],
                "mass": acts[k]["mass"],
            }
            for k in dict.fromkeys(m["model"] for m in robot["motors"])
        },
        "motor_of": motor_of,
        "coupled": robot.get("coupled_limits", []),
        "stance": dict(robot["stance"]),
        "pelvis_height": robot["stance_pelvis_height"],
        "sole_below_ankle": robot["dimensions"]["ankle_height"],
        "foot": [robot["dimensions"]["foot_length"], robot["dimensions"]["foot_width"]],
        "source": SOURCE,
        "bin": base64.b64encode(bytes(blob)).decode(),
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(model, separators=(",", ":"))
    out.write_text(f"/* Marvin Bot Mini 3-D model data. {SOURCE} */\nwindow.MARVIN_MODEL={body};\n")
    print(f"{len(parts)} parts, {total} triangles in, {len(blob) / 1e6:.2f} MB -> {out}")


if __name__ == "__main__":
    main()
