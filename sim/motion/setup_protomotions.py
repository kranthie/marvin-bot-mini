REWARDS = '''"""Extra reward terms for Marvin Bot Mini's tracker.

Generated by sim/motion/setup_protomotions.py (marvin-bot-mini).
"""

import torch
from torch import Tensor


def compute_joint_pos_rew(
    current_dof_pos: Tensor, ref_dof_pos: Tensor, sigma: float, joints: list[int]
) -> Tensor:
    """exp(-mean squared joint-angle error / sigma^2), over the given joints."""
    err = current_dof_pos[..., joints] - ref_dof_pos[..., joints]
    return torch.exp(-(err**2).mean(-1) / sigma**2)


def compute_servo_load_rew(
    dof_pos: Tensor,
    dof_vel: Tensor,
    pd_target: Tensor | None,
    kp: list[float],
    kd: list[float],
    effort: list[float],
    rated: list[float],
    free: float,
) -> Tensor:
    """Sum over joints of (|torque| / rated - free)^2 where positive: the servos' load.

    The torque is the joint PD's (kp (target - q) - kd q', capped at effort), worked out here
    because the simulator's built-in PD does not report it."""
    if pd_target is None:
        return torch.zeros(dof_pos.shape[0], device=dof_pos.device)
    t = lambda x: torch.tensor(x, device=dof_pos.device, dtype=dof_pos.dtype)  # noqa: E731
    tau = (t(kp) * (pd_target - dof_pos) - t(kd) * dof_vel).clamp(-t(effort), t(effort))
    return ((tau.abs() / t(rated) - free).clamp(min=0) ** 2).sum(-1)
'''

