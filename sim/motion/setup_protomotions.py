"""Add Marvin Bot Mini to a ProtoMotions checkout: its MJCF, a retargeting URDF and a robot config.

ProtoMotions (github.com/NVlabs/ProtoMotions) trains motion-tracking policies from human motion
retargeted to a robot. Everything written here is generated from the description, so rerun this
after any change to it (as tools/build_urdf.py is rerun). Adapted from Marvin Bot's.

  protomotions/data/assets/mjcf/marvin_bot_mini.xml      the robot for simulation: the URDF's
      links, inertias and collision boxes, a free base, the servos' armature and stall torque,
      and a 1 g hand body at the end of each forearm (the mini has no wrists), which the tracker
      scores; the arms collide with the body and each other
  protomotions/data/assets/urdf/for_retargeting/marvin_bot_mini.urdf
      the URDF without visuals, plus the frames the retargeter matches human keypoints to: a toe
      6 cm ahead of each ankle, a hand frame at each forearm's end pointing down it, and a torso
      frame (see TORSO_FRAME)
  protomotions/robot_configs/marvin_bot_mini.py     joint gains, effort and speed limits, stance,
      the bodies tracked, and registration in robot_configs/factory.py
  examples/experiments/mimic/mlp_bm_marvin_bot_mini.py   the tracker: upstream's mlp_bm_l2c2.py
      (BeyondMimic) with the changes in EXPERIMENT_EDITS
  protomotions/envs/rewards/marvin_bot_mini.py       the tracker's extra reward terms

The servos are ProtoMotions' built-in PD standing in for the servo model (sim/servo_model.py):
at small errors the servo is a PD with stiffness kt * firmware_kp * error_gain * v / R and
damping kt² / R, its torque capped at stall, at the pack's nominal voltage (joint_specs()).
sim/motion/replay_mujoco.py checks the tracker on the full servo model.

Usage (in the ProtoMotions environment, which has mujoco and pyyaml):
  python sim/motion/setup_protomotions.py /path/to/ProtoMotions
"""

