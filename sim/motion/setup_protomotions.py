def joint_specs() -> dict[str, dict]:
    """Per joint: the servo as an equivalent PD at the nominal pack voltage (stiffness, damping),
    its stall torque (effort), no-load speed and rated torque at that voltage, and armature."""
    out = {}
    for m in _robot["motors"]:
        a = _acts[m["model"]]
        sm = a["model"]
        v = V_NOMINAL / a["v_rated"]
        for side in SIDES if "{side}" in m["name"] else (None,):
            (j,) = (d.replace("{side}", side) if side else d for d in m["drives"])
            out[j] = dict(
                kp=round(sm["kt"] * sm["firmware_kp"] * sm["error_gain"] * V_NOMINAL / sm["R"], 3),
                kd=round(sm["kt"] ** 2 / sm["R"], 4),
                effort=a["stall_torque"] * v,
                speed=a["no_load_speed_rpm"] * 2 * math.pi / 60 * v,
                rated=a["rated_torque"],
                armature=sm["armature"],
                friction=0.0,
            )
    return out


