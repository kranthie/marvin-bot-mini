"""Build the code-CAD parts: meshes, mass properties and a printer size check.

Writes:
  description/meshes/<part>.stl   each part in its link's frame (m), for the URDF's visuals
  description/cad_model.yaml      per part: link, material, process, mass budget item, mass,
                                  centre of mass and inertia (link frame, SI), size (mm)

tools/build_urdf.py takes the CAD parts' masses and inertias in place of skeleton.yaml's
estimate boxes for the budget items they cover, and shows their meshes. The left parts in
cad/parts.py are mirrored for the right side. Masses are for solid printed walls (the parts
are modelled at their wall thickness, which prints as solid perimeters). Adapted from Marvin
Bot's cad/build.py.

Usage:
  python -m cad.build            # write meshes and cad_model.yaml, print the part table
  python -m cad.build --check    # exit 1 if cad_model.yaml is out of date (CI)

Needs: pip install -e ".[cad]"
"""

import argparse
import sys
import tempfile
from pathlib import Path

import trimesh
import yaml
from build123d import Plane, export_stl

from .parts import PARTS

ROOT = Path(__file__).resolve().parent.parent
MESHES = ROOT / "description" / "meshes"
MODEL = ROOT / "description" / "cad_model.yaml"
PRINT_MM = (220.0, 220.0, 220.0)  # a common desktop printer's build volume
DENSITY = {"petg": 1270.0, "pa_cf": 1200.0, "tpu": 1210.0}  # kg/m³, solid
HEADER = """# Generated by cad/build.py from the code-CAD parts in cad/. Do not edit.
# Per part: mass (kg), centre of mass and inertia about it (ixx iyy izz ixy ixz iyz,
# link frame, SI), size (mm), and the mass budget item it covers.
"""


def mirror_name(name: str) -> str:
    return "right_" + name[len("left_") :]


def mesh_of(solid) -> trimesh.Trimesh:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "part.stl"
        export_stl(solid, str(path), tolerance=0.05, angular_tolerance=0.2)
        mesh = trimesh.load(path)
    mesh.apply_scale(0.001)
    return mesh


def parts():
    """(name, solid, link, material, budget) for every part, the right side mirrored."""
    for name, (fn, link, material, budget) in PARTS.items():
        solid = fn()
        yield name, solid, link, material, budget
        if name.startswith("left_"):
            yield mirror_name(name), solid.mirror(Plane.XZ), mirror_name(link), material, budget


def build(write_meshes: bool) -> tuple[str, list[str]]:
    model = {}
    errors = []
    if write_meshes:
        MESHES.mkdir(parents=True, exist_ok=True)
    for name, solid, link, material, budget in parts():
        mesh = mesh_of(solid)
        if not mesh.is_watertight:
            errors.append(f"{name}: mesh is not watertight")
        mesh.density = DENSITY[material]
        size = sorted(round(v, 1) for v in (mesh.extents * 1000))
        if any(s > p for s, p in zip(size, sorted(PRINT_MM), strict=True)):
            errors.append(f"{name}: {size} mm does not fit the printer {PRINT_MM}")
        i = mesh.moment_inertia
        model[name] = {
            "link": link,
            "material": material,
            "process": "print",
            "budget": budget,
            "mass": round(float(mesh.mass), 5),
            "com": [round(float(v), 7) for v in mesh.center_mass],
            "inertia": [
                float(f"{v:.6g}") for v in (i[0, 0], i[1, 1], i[2, 2], i[0, 1], i[0, 2], i[1, 2])
            ],
            "size_mm": [round(float(v), 1) for v in mesh.extents * 1000],
        }
        if write_meshes:
            mesh.export(MESHES / f"{name}.stl")
    text = HEADER + yaml.safe_dump(model, sort_keys=False, default_flow_style=None, width=100)
    return text, errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if cad_model.yaml is out of date")
    args = ap.parse_args()
    text, errors = build(write_meshes=not args.check)
    for e in errors:
        print(f"ERROR: {e}")
    if args.check:
        if not MODEL.exists() or MODEL.read_text() != text:
            print("description/cad_model.yaml is out of date: run python -m cad.build")
            return 1
        print("cad_model.yaml up to date")
        return 1 if errors else 0
    MODEL.write_text(text)
    model = yaml.safe_load(text)
    by_budget: dict[str, float] = {}
    print(f"{'part':26} {'material':8} {'g':>6}  size mm")
    for name, p in model.items():
        by_budget[p["budget"]] = by_budget.get(p["budget"], 0.0) + p["mass"]
        print(f"{name:26} {p['material']:8} {p['mass'] * 1000:6.1f}  {p['size_mm']}")
    for k, v in by_budget.items():
        print(f"{k}: {v:.4f} kg")
    print(f"wrote {MODEL.relative_to(ROOT)} and {len(model)} meshes")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
